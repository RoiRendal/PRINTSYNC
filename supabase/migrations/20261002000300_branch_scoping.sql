-- cannot be deleted while any profile still references it, and without this index
-- that check scans every row of `profiles`. The migration-replay gate flagged it
-- as the one remaining "foreign key with no usable index", which is how it was
-- found rather than by reading. It sits in the Phase 2 migration because that is
-- the file that completes the branch schema, even though the column is Phase 1's.
create index if not exists profiles_branch_id_idx
  on public.profiles (branch_id);

-- ─── 3. Per-branch document numbering ───────────────────────────────────────
--
-- Today a document's reference is `PS-` + the last 8 characters of its uuid,
-- derived in the browser (`OrdersTable.tsx`). That is fine for one shop and
-- useless for two: the number carries no branch and cannot be read aloud on a
-- phone to the other branch. The owner accepted `BAL-0001` / `NAS-0001`.
--
-- The number is generated *in the database*, inside the same statement that
-- creates the row, using a per-branch counter. Two properties matter and both are
-- why this is not computed from `count(*)`:
--
--   * **It never repeats**, even under concurrency. `count(*) + 1` gives two
--     orders the same number when two cashiers save at once; a sequence does not.
--   * **It never goes backwards.** Deleting order 7 must not make the next order
--     reuse "7". A counter that only moves forward gives an auditor a stable
--     reference.
--
-- The counter lives in `branch_counters`, one row per (branch, document type), so
-- orders and sales can number independently. `next_document_number` takes a row
-- lock for the duration of its own statement, so two concurrent creators in the
-- same branch are serialised on that one row and cannot draw the same value.

create table if not exists public.branch_counters (
  branch_id uuid not null references public.branches(id) on delete restrict,
  document_type text not null check (length(btrim(document_type)) > 0),
  last_number integer not null default 0 check (last_number >= 0),
  primary key (branch_id, document_type)
);

alter table public.branch_counters enable row level security;

-- Read-only to authenticated clients, like every other table in this schema; all
-- writes go through the service role via `next_document_number`.
create policy "authenticated users can read branch counters"
on public.branch_counters for select
to authenticated
using (true);

grant select on public.branch_counters to authenticated;
grant select, insert, update, delete on public.branch_counters to service_role;

comment on table public.branch_counters is
  'Monotonic per-branch document counters. One row per (branch, document type). Read by next_document_number, which is the only writer.';

-- Allocates the next number for one branch and document type, and returns it.
--
-- `insert ... on conflict do update ... returning` is one atomic statement. The
-- `update` inside the conflict clause takes a row lock, so a second caller blocks
-- until the first commits and then increments from the committed value — the two
-- cannot both read `n` and both return `n + 1`. This is why the counter is a row
-- and not a Postgres `sequence`: a sequence is global to the column and cannot be
-- partitioned per branch without one sequence per branch, which is DDL at
-- runtime.
create or replace function public.next_document_number(
  p_branch_id uuid,
  p_document_type text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  allocated integer;
  branch_code text;
begin
  if p_branch_id is null then
    raise exception 'A branch is required to allocate a document number';
  end if;

  -- Lock the branch row itself so the code read below cannot race a rename.
  select code into branch_code
  from public.branches
  where id = p_branch_id
  for share;

  if branch_code is null then
    raise exception 'Branch % does not exist', p_branch_id;
  end if;

  insert into public.branch_counters (branch_id, document_type, last_number)
  values (p_branch_id, btrim(p_document_type), 1)
  on conflict (branch_id, document_type)
    do update set last_number = public.branch_counters.last_number + 1
  returning last_number into allocated;

  -- Zero-padded to four digits, matching the `BAL-0001` shape the owner accepted.
  -- Past 9999 the padding simply widens (`BAL-10000`); a print shop will not
  -- reach five digits in a year, but wrapping would be worse than a wider number.
  return branch_code || '-' || lpad(allocated::text, 4, '0');
end;
$$;

revoke all on function public.next_document_number(uuid, text) from public, anon, authenticated;
grant execute on function public.next_document_number(uuid, text) to service_role;

-- The documents that get a human reference. Both columns are nullable: they are
-- written by the creating RPC going forward, and a replay of an already-created
-- row does not retroactively renumber it (the number was never allocated for it,
-- and inventing one now would break the "never goes backwards" guarantee because
-- the counter would have to jump past every existing row's absent number).
alter table public.orders
  add column if not exists reference text;
alter table public.sales_transactions
  add column if not exists reference text;

comment on column public.orders.reference is
  'Human-readable document number (`BAL-0001`). Null for orders created before Phase 2; those remain addressable by uuid.';
comment on column public.sales_transactions.reference is
  'Human-readable receipt number (`BAL-0001`). Null for sales created before Phase 2.';

-- A branch cannot issue the same reference twice, and the unique index is what
-- makes that a database guarantee rather than a convention. Partial, because
-- every pre-Phase-2 row is null and nulls would otherwise all collide... except
-- they do not: a plain unique index already treats nulls as distinct. The
-- predicate is kept to document that only allocated numbers are covered.
create unique index if not exists orders_reference_key
  on public.orders (reference) where reference is not null;
create unique index if not exists sales_transactions_reference_key
  on public.sales_transactions (reference) where reference is not null;

-- ─── 4. Seed Nasugbu's catalogue as a copy of Balayan's ─────────────────────
--
-- The owner chose "a copy" for the catalogue. Designs are copied as rows so
-- Nasugbu can edit or delete its own without touching Balayan's — a shared row
-- would mean one branch deleting a design the other still sells. The image is
-- referenced by URL, so a copy points at the same stored file; that is intended,
-- the artwork is the same artwork, and only the *listing* is per-branch.
--
-- Guarded on Nasugbu having no designs at all, so re-running is a no-op and a
-- later Nasugbu that has curated its own catalogue is never re-seeded.
insert into public.designs (name, category, image_url, asset_type, asset_size_bytes, branch_id, created_by)
select d.name, d.category, d.image_url, d.asset_type, d.asset_size_bytes,
       (select id from public.branches where code = 'NAS'),
       d.created_by
from public.designs d
where d.branch_id = (select id from public.branches where code = 'BAL')
  and not exists (
    select 1 from public.designs n
    where n.branch_id = (select id from public.branches where code = 'NAS')
  );

