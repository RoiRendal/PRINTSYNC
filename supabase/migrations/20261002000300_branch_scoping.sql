-- Branch scoping: tag every operational row with the branch that owns it.
--
-- This is Phase 2 of the two-branch rollout, and it runs immediately after
-- 20261002000200_branches.sql. Phase 1 created `branches` and made the *settings*
-- per-branch; **Phase 2 makes the data per-branch**. Nothing here enforces the
-- boundary yet — a query that forgets its `branch_id` filter still returns both
-- shops' rows until Phase 3 adds the predicates and the negative tests. That is
-- deliberate: this migration is additive and reversible, and the enforcement
-- migration can be reviewed on its own.
--
-- Plan of record: 0_never-push-this-dump-folder/printsync-two-branch-plan.md
--
-- ## What "scoped" means for each table, and why not all of them get a column
--
-- There are two ways a table can belong to a branch:
--
--   * **Owned** — the row *is* the thing (an order, a customer, a design), so it
--     carries `branch_id` directly. These are the tables staff list, create and
--     delete: `orders`, `sales_transactions`, `inventory_items`, `designs`,
--     `customers`, `suppliers`, `purchase_orders`, `operating_expenses`.
--
--   * **Inherited** — the row is a child whose parent already carries the branch,
--     so it gets NO column. Adding one would create a second copy of the same
--     fact, and the two copies can disagree: an `order_items` row could claim
--     Nasugbu while its `orders` row says Balayan. The parent is the single
--     source of truth, and every read of a child joins or filters through the
--     parent's id, which is already indexed. These tables are: `order_items`
--     (→ `orders`), `sales_transaction_items` (→ `sales_transactions`),
--     `payments` (→ `sales_transactions`), `order_payments` (→ `orders`),
--     `inventory_movements` (→ `inventory_items`).
--
-- The owner's rule — "stock is kept entirely separate per branch" — is satisfied
-- by the *owned* column on `inventory_items`: two branches can each have a ream
-- of A4 without either one's stock moving when the other sells. The movement log
-- inherits, so stock moved at Nasugbu is visible as Nasugbu's because the item
-- it belongs to is Nasugbu's.
--
-- ## Why nothing is unique-per-branch here
--
-- `inventory_items.sku` is `unique` globally today. Two branches legitimately
-- want their own `SKU-001`, but making that unique per branch is a *behaviour*
-- change that belongs with the enforcement work, and doing it now would silently
-- start rejecting a duplicate that the current catalogue already permits. Phase 3
-- converts `unique (sku)` to `unique (branch_id, sku)`. This migration adds the
-- column and nothing else, so a replay is a pure superset of the current schema.
--
-- ## Backfill
--
-- Every existing row is Balayan's. That is not an assumption: the shop has run
-- from one site, all 867 sales, 23 orders, 30 customers, 15 stock items and 6
-- suppliers in the live database were entered there, and Phase 1 assigned every
-- current profile to Balayan. Nasugbu starts with an empty book, which is what
-- the owner asked for ("Nasugbu's stock starts empty").

-- ─── 1. The eight owned tables ──────────────────────────────────────────────
