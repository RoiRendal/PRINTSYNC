-- ─── 5. Tighten profile membership ──────────────────────────────────────────
--
-- Phase 1 left `profiles.branch_id` nullable because the auth row is created
-- before the profile row, so a profile can briefly not exist — but a profile that
-- *exists* without a branch is an account that can log in and see nothing or
-- everything, depending on how Phase 3 fails. Now that every operational table
-- demands a branch, an account without one has no coherent place in the system,
-- so the column is tightened here, in the same migration that gives the data its
-- branch. The insert path was made to always write one in Phase 1's service
-- changes; this makes the database refuse the alternative.
alter table public.profiles
  alter column branch_id set not null;

-- ─── 6. Grants for the new column are implicit ──────────────────────────────
--
-- Columns added to a table are covered by that table's existing table-level
-- grants, so `select/insert/update/delete on public.orders to service_role`
-- already includes `branch_id`. No new grant is needed, and adding one would be
