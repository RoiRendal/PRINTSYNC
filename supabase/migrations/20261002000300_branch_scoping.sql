-- every *future* insert silently land in Balayan unless it opted out, which is
-- exactly the failure this whole phase exists to prevent. Instead the column is
-- added nullable, backfilled explicitly, then tightened to `not null` — so a
-- write that forgets its branch is rejected by the database rather than filed in
-- the wrong shop. (Phase 3 makes the API always send one; Phase 2 makes the
-- database refuse to invent one.)

